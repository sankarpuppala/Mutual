import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import {
  PROTOCOL_VERSION,
  ProtocolError,
  b64urlDecode,
  b64urlEncode,
  eid,
  encounterToken,
  ephemeralPrivateKey,
  interestToken,
  isValidPublicKey,
  pairKey,
  toHex,
  uidBytes,
} from '../src/index';

const path = fileURLToPath(new URL('../../protocol-spec/vectors.json', import.meta.url));
// `any` because vectors.json is untyped JSON produced by protocol_py; every field is checked below.
const v: any = JSON.parse(readFileSync(path, 'utf8'));
const h = (s: string): Uint8Array => Uint8Array.from(s.match(/../g) ?? [], (b) => parseInt(b, 16));

describe('cross-language vectors (generated by protocol_py)', () => {
  it('has the same protocol version and at least 100 cases', () => {
    expect(v.protocol_version).toBe(PROTOCOL_VERSION);
    const n = Object.values(v).filter(Array.isArray).reduce((a: number, x) => a + (x as unknown[]).length, 0);
    expect(n).toBeGreaterThanOrEqual(100);
  });

  it('base64url', () => {
    for (const c of v.base64url) {
      expect(b64urlEncode(h(c.bytes))).toBe(c.b64url);
      expect(toHex(b64urlDecode(c.b64url))).toBe(c.bytes);
    }
  });

  it('uid bytes', () => {
    for (const c of v.uid_bytes) expect(toHex(uidBytes(c.uid))).toBe(c.bytes);
  });

  it('pair key, from both sides', () => {
    for (const c of v.pair_key) {
      expect(toHex(pairKey(h(c.sk_a), h(c.pk_a), c.uid_a, h(c.pk_b), c.uid_b))).toBe(c.pair_key);
      expect(toHex(pairKey(h(c.sk_b), h(c.pk_b), c.uid_b, h(c.pk_a), c.uid_a))).toBe(c.pair_key);
    }
  });

  it('interest token', () => {
    for (const c of v.interest_token) {
      expect(toHex(interestToken(h(c.pair_key), c.epoch, c.intent))).toBe(c.token);
      expect(toHex(interestToken(h(c.pair_key), c.epoch, c.intent_code))).toBe(c.token);
    }
  });

  it('ephemeral private key and EID', () => {
    for (const c of v.eid) {
      expect(toHex(ephemeralPrivateKey(h(c.daily_key), c.interval))).toBe(c.esk);
      expect(toHex(eid(h(c.daily_key), c.interval))).toBe(c.eid);
    }
  });

  it('encounter token, from both devices', () => {
    for (const c of v.encounter_token) {
      expect(toHex(encounterToken(c.day, h(c.esk_a), h(c.eid_a), h(c.eid_b)))).toBe(c.token);
      expect(toHex(encounterToken(c.day, h(c.esk_b), h(c.eid_b), h(c.eid_a)))).toBe(c.token);
    }
  });

  it('public key validity', () => {
    for (const c of v.public_key_validity) expect(isValidPublicKey(h(c.public_key))).toBe(c.valid);
  });

  it('error cases fail the same way', () => {
    for (const c of v.errors) {
      const run = (): unknown => {
        if (c.op === 'pair_key') return pairKey(h(c.sk_self), h(c.pk_self), c.uid_self, h(c.pk_peer), c.uid_peer);
        if (c.op === 'encounter_token') return encounterToken(c.day, h(c.esk_own), h(c.eid_own), h(c.eid_heard));
        return interestToken(h(c.pair_key), c.epoch, c.intent);
      };
      expect(run, c.why).toThrow(ProtocolError);
    }
  });
});
